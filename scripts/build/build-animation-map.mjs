// Compile the owner-approved design allocation into its single runtime index.
// Media bytes are read only for hashes and container timing; no media is generated.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {resolve,join,basename} from 'node:path';
import {createHash} from 'node:crypto';
import {webmDurationMs} from '../lib/webm-metadata.mjs';
const root=resolve(import.meta.dirname,'../..');
const read=name=>JSON.parse(readFileSync(join(root,name),'utf8'));
const design=read('src/living/body/animation-allocation.json');
const catalog=read('src/desktop/assets/catalog.json');
const supplementary=read('src/desktop/assets/life-animations.json');
const mediaRoot=join(root,'src/desktop/assets');
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const actions=new Map(catalog.actions.map(row=>[row.id,row]));
if(actions.size!==catalog.actions.length)throw Error('Duplicate animation id');
const aliases=[];
for(const row of design.room_aliases){
  let file=join(root,'vendor/feiyu-room-template/public/room',row.url);
  if(!existsSync(file))file=join(mediaRoot,basename(row.url)==='react_pout.webm'?'点击回应-傲娇生气.webm':basename(row.url));
  if(!existsSync(file))throw Error('Missing registered Room media: '+row.key);
  aliases.push({...row,hash:hash(readFileSync(file))});
}
// Keep current canonical names, including the hurry alias instead of walk_fast.
aliases.sort((a,b)=>(a.key==='run_hurry'?-1:b.key==='run_hurry'?1:0));
const life=new Map(supplementary.animations.map(row=>[row.id,row]));
const assets={},filesByHash=new Map();
for(const row of catalog.actions){
  if(/[\\/]|^\.|\.\./.test(row.id))throw Error('Unsafe animation id: '+row.id);
  const file=join(mediaRoot,row.file);if(!existsSync(file))throw Error('Missing animation file: '+row.file);
  const bytes=readFileSync(file),digest=hash(bytes),durationMs=webmDurationMs(bytes,row.file);
  filesByHash.set(digest,row.file);const alias=aliases.find(entry=>entry.hash===digest);
  const extra=life.get(row.id);
  if(extra&&(extra.file!==row.file||extra.sha256!==digest||extra.bytes!==bytes.length||extra.durationMs!==durationMs))
    throw Error('Life media timing/manifest mismatch: '+row.id);
  assets[row.id]={id:row.id,roomClip:alias?.key ?? 'mapped-'+row.id,desktopClip:row.label,file:row.file,
    ...(extra?.poster?.file?{posterFile:extra.poster.file}:{}),durationMs,
    ...(['吃饭·碗饭','吃饭团','期待开饭'].includes(row.id)?{composition:row.id==='吃饭·碗饭'?'baifan-bowl':row.id==='吃饭团'?'baifan-riceball':'baifan-wait'}:{})};
}
const roomAliases=Object.fromEntries(aliases.map(alias=>{
  const file=filesByHash.get(alias.hash);
  if(!file)throw Error('Room alias has no registered Desktop source: '+alias.key);
  return [alias.url,file];
}));
const stickers=Object.fromEntries(catalog.stickers.map(row=>[row.label,{id:row.id,label:row.label,file:row.file}]));
const slots={};
for(const row of design.slots){
  if(slots[row.id])throw Error('Duplicate animation slot: '+row.id);
  if(row.clips.some(id=>!assets[id])||row.stickers.some(label=>!stickers[label]))throw Error('Invalid animation slot reference: '+row.id);
  slots[row.id]={id:row.id,clips:row.clips,match:row.match,uncovered:row.uncovered,stickers:row.stickers,
    ...(row.body_source?{bodySource:row.body_source}:{}),
    ...(row.selected_food_position!==undefined?{selectedFoodPosition:row.selected_food_position}:{}),
    ...(row.transform_candidate?{mirror:true}:{})};
}
const output=`// Generated by scripts/build/build-animation-map.mjs from the approved name map.\n// This index chooses media only; it never admits an activity or settles effects.\nexport interface AnimationAsset {id:string;roomClip:string;desktopClip:string;file:string;posterFile?:string;durationMs:number;composition?:string}\nexport interface AnimationSlot {id:string;clips:string[];match:'direct'|'combined'|'proxy'|'blank';uncovered:string[];stickers:string[];bodySource?:'current'|'return';selectedFoodPosition?:number;mirror?:boolean}\nexport interface AnimationSticker {id:string;label:string;file:string}\nexport const animationAssets:Record<string,AnimationAsset> = ${JSON.stringify(assets,null,2)};\nexport const animationSlots:Record<string,AnimationSlot> = ${JSON.stringify(slots,null,2)};\nexport const animationStickers:Record<string,AnimationSticker> = ${JSON.stringify(stickers,null,2)};\nexport const animationRoomAliases:Record<string,string> = ${JSON.stringify(roomAliases,null,2)};\n`;
writeFileSync(join(root,'src/living/body/animation-map.ts'),output);
writeFileSync(join(root,'src/living/body/animation-slot-ids.ts'),
  '// Generated by scripts/build/build-animation-map.mjs from the approved name map.\n'
  + 'export const registeredAnimationSlots: ReadonlySet<string> = new Set(' + JSON.stringify(Object.keys(slots)) + ');\n');
console.log(JSON.stringify({animationAssets:Object.keys(assets).length,animationSlots:Object.keys(slots).length,animationStickers:Object.keys(stickers).length}));
